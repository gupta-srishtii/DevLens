import type { Analysis } from "./types";

function plain(value: string) { return value.replace(/[\r\n]+/g, " ").replace(/[\\`*_{}\[\]<>|#!]/g, ""); }

export function markdownReport(analysis: Analysis) {
  const { repository: repo, health, scope } = analysis;
  return [
    `# ${plain(repo.full_name)} — DevLens report`, "",
    `Source: https://github.com/${repo.full_name}`, `Assembled: ${analysis.fetchedAt}`, `Upstream responses cached for up to ${analysis.cacheSeconds} seconds; this is not a commit-pinned snapshot.`, "",
    plain(repo.description ?? "No description provided."), "", "## Repository", "",
    `- Stars: ${repo.stargazers_count}`, `- Forks: ${repo.forks_count}`, `- Open issues + pull requests: ${repo.open_issues_count}`, `- Default branch: ${plain(repo.default_branch)}`, `- License: ${plain(repo.license?.name ?? "Not detected")}`, `- Archived: ${repo.archived ? "Yes" : "No"}`, "",
    "## Languages (GitHub Linguist bytes)", "",
    ...(analysis.languages?.map((language) => `- ${plain(language.name)}: ${language.percentage.toFixed(1)}% (${language.bytes} bytes)`) ?? ["Unavailable."]), "",
    "## Maintenance signals", "",
    `Checklist score: ${health.score === null ? "Unavailable" : `${health.score}/100`} (${health.earned}/${health.available} assessed points). This is not a code quality, security, or project suitability assessment.`, "",
    ...health.signals.map((signal) => `- ${signal.passed === null ? "Unknown" : signal.passed ? "Present" : "Not detected"}: ${signal.label} (${signal.points} points). ${signal.reason}`), "",
    "## Activity and collaboration", "",
    `- Commits in sample: ${analysis.commits?.length ?? "Unavailable"}`, `- Contributors returned: ${analysis.contributors?.length ?? "Unavailable"}`, `- Issues in sample: ${analysis.issues?.length ?? "Unavailable"}`, `- Pull requests in sample: ${analysis.pulls?.length ?? "Unavailable"}`, "",
    "## Methodology and scope", "",
    ...Object.entries(scope).map(([name, value]) => `- ${name}: ${value}`), "",
    "## Technology evidence", "",
    ...analysis.technologies.map((technology) => `- ${plain(technology.name)}: root file ${plain(technology.evidence)}`), "",
    "## Warnings", "", ...(analysis.warnings.length ? analysis.warnings.map((warning) => `- ${plain(warning)}`) : ["No upstream warnings at analysis time."]), "",
    "Generated by DevLens. No AI-generated metrics. No credentials included.", "",
  ].join("\n");
}

export function downloadReport(analysis: Analysis, format: "json" | "md") {
  const body = format === "json" ? JSON.stringify(analysis, null, 2) : markdownReport(analysis);
  downloadText(body, `devlens-${analysis.repository.full_name.replace("/", "-")}.${format}`, format === "json" ? "application/json" : "text/markdown;charset=utf-8");
}

export function downloadComparison(left: Analysis, right: Analysis) {
  const body = `# DevLens repository comparison\n\nBoth repositories use the same bounded sampling methodology. Scores may have different assessed denominators. There is no universal winner.\n\n${markdownReport(left)}\n---\n\n${markdownReport(right)}`;
  downloadText(body, "devlens-comparison.md", "text/markdown;charset=utf-8");
}

function downloadText(body: string, filename: string, type: string) {
  const blob = new Blob([body], { type });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link); link.click(); link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
